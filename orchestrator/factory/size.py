"""The size of a change, counted the way a reviewer feels it: hand-written lines.

Size counts changed lines (added plus removed), tests included, and excludes generated files: a path marked
`linguist-generated` in the repository's `.gitattributes`, a lockfile, or a path the spec declares as regenerated by a
named command (`regenerated: [{paths, command}]`). Budgets per size (defaults XS ≤ 50, S ≤ 150, M ≤ 400) live in
`Policy.size_budget_lines` and `FACTORY_SIZE_BUDGET`. The decomposer and the spec writer estimate with this definition,
the spec judge rejects an estimate above M, and the merge-time `size_budget` check reports the measured split against
the estimate; an overrun is a flag for the owner, never another round. Post-mortem 2026-10-11 §3: a 71-line change
picked up 7,604 regenerated lines and a 1,860-line test and still read as size S.
"""
from __future__ import annotations

import fnmatch
import subprocess
from pathlib import Path
from typing import Any

DEFAULT_BUDGET = {"XS": 50, "S": 150, "M": 400}
SIZES = ("XS", "S", "M", "L")
LOCKFILES = {"package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb", "deno.lock",
             "poetry.lock", "uv.lock", "Pipfile.lock", "pdm.lock", "Cargo.lock", "Gemfile.lock", "composer.lock", "go.sum",
             "mix.lock", "flake.lock", "packages.lock.json", "gradle.lockfile", "Package.resolved", "pubspec.lock"}
ATTRIBUTE = "linguist-generated"


def parse_budget(text: str | None) -> dict[str, int]:
    """`FACTORY_SIZE_BUDGET="XS=50,S=150,M=400"` -> {"XS": 50, "S": 150, "M": 400}; missing sizes keep their defaults.
    A part that does not read `<size>=<whole number>` is an error, like every other numeric knob, never a silent default."""
    budget = dict(DEFAULT_BUDGET)
    for part in (text or "").split(","):
        if not part.strip():
            continue
        name, _, value = part.partition("=")
        if name.strip().upper() not in budget or not (value.strip().isascii() and value.strip().isdecimal()):
            raise ValueError(f"FACTORY_SIZE_BUDGET part {part.strip()!r} is not XS=<n>, S=<n> or M=<n>")
        budget[name.strip().upper()] = int(value)
    if not budget["XS"] < budget["S"] < budget["M"]:
        raise ValueError(f"size budget must grow XS < S < M, got {budget}")
    return budget


def size_for(lines: int, budget: dict[str, int]) -> str:
    return next((s for s in ("XS", "S", "M") if lines <= budget[s]), "L")


def describe_budget(budget: dict[str, int]) -> str:
    return f"XS ≤ {budget['XS']}, S ≤ {budget['S']}, M ≤ {budget['M']}"


# ---------------------------------------------------------------------------------------------------- generated files

def gitattributes_rules(text: str | None) -> list[tuple[str, bool]]:
    """(pattern, generated) for every .gitattributes line that sets or unsets linguist-generated, in file order (the
    last matching line wins, as in git)."""
    rules = []
    for line in (text or "").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        pattern, *attrs = line.split()
        for attr in attrs:
            name, _, value = attr.lstrip("-!").partition("=")
            if name != ATTRIBUTE:
                continue
            unset = attr.startswith(("-", "!")) or value.lower() in ("false", "0", "no")
            rules.append((pattern, not unset))
    return rules


def _matches(pattern: str, path: str) -> bool:
    """A spec's `regenerated` glob: `dir/` means everything under it."""
    pattern = pattern.lstrip("/")
    if "/" not in pattern.rstrip("/"):
        return fnmatch.fnmatchcase(path.rsplit("/", 1)[-1], pattern) or (pattern.endswith("/") and f"/{pattern}" in f"/{path}")
    if pattern.endswith("/"):
        pattern += "**"
    from .checks import _glob_to_regex
    return bool(_glob_to_regex(pattern).match(path))


def _attribute_matches(pattern: str, path: str) -> bool:
    """A .gitattributes pattern as git reads it (gitattributes(5)): a pattern ending in `/` matches no file, a leading
    `/` anchors at the root, a pattern without a slash matches the basename at any depth. Used only where there is no
    repository to ask (an onboarding proposal); a real checkout is asked with `git check-attr` (`attributes_at`)."""
    if pattern.endswith("/"):
        return False
    anchored = pattern.startswith("/")
    pattern = pattern.lstrip("/")
    if "/" not in pattern and not anchored:
        return fnmatch.fnmatchcase(path.rsplit("/", 1)[-1], pattern)
    from .checks import _glob_to_regex
    return bool(_glob_to_regex(pattern).match(path))


def generated_reason(path: str, rules: list[tuple[str, bool]], regenerated: list[dict[str, Any]],
                     state: str | None = None) -> tuple[str, str | None] | None:
    """Why `path` is generated, as (reason, command), or None when it is hand-written. `state` is git's own answer for
    linguist-generated (`set`, `unset`, `unspecified`, or a value); without it the `rules` of one .gitattributes text
    are matched instead."""
    for entry in regenerated:
        if any(_matches(g, path) for g in entry.get("paths") or []):
            return "declared regenerated by the spec", str(entry.get("command") or "") or None
    marked = None
    if state is not None:
        marked = None if state == "unspecified" else state not in ("unset", "false", "0", "no")
    else:
        for pattern, generated in rules:
            if _attribute_matches(pattern, path):
                marked = generated
    if marked:
        return "marked linguist-generated in .gitattributes", None
    if marked is None and path.rsplit("/", 1)[-1] in LOCKFILES:
        return "lockfile", None
    return None


def measure(diff_stats: dict[str, Any] | None, *, gitattributes: str | None = None,
            regenerated: list[dict[str, Any]] | None = None, attributes: dict[str, str] | None = None) -> dict[str, Any] | None:
    """Split a diff's changed lines into hand-written (app and tests) and generated. `attributes` is git's own
    linguist-generated state per path (`attributes_at`); `gitattributes` is a fallback text when there is none."""
    if diff_stats is None:
        return None
    from .checks import is_test_file
    rules = gitattributes_rules(gitattributes)
    out = {"hand_written": 0, "app": 0, "tests": 0, "generated": 0, "generated_files": [], "commands": [], "files": []}
    for f in diff_stats.get("files", []):
        lines = int(f.get("added", 0)) + int(f.get("removed", 0))
        state = (attributes or {}).get(f["path"], "unspecified") if attributes is not None else None
        why = generated_reason(f["path"], rules, regenerated or [], state)
        if why is not None:
            out["generated"] += lines
            out["generated_files"].append({"path": f["path"], "lines": lines, "reason": why[0]})
            if why[1] and why[1] not in out["commands"]:
                out["commands"].append(why[1])
            kind = "generated"
        else:
            kind = "tests" if is_test_file(f["path"]) else "app"
            out[kind] += lines
            out["hand_written"] += lines
        out["files"].append({"path": f["path"], "lines": lines, "kind": kind})
    return out


# ---------------------------------------------------------------------------------------------------- reading git

def numstat(repo: Path, base: str, head: str) -> dict[str, Any] | None:
    """`git diff --numstat -z base..head` as totals and per-file rows: a rename is counted under its new path, paths are
    exactly git's (no C-quoting), binary files count as zero lines. None when git cannot say."""
    try:
        raw = subprocess.run(["git", "diff", "--numstat", "-z", f"{base}..{head}"], cwd=repo, capture_output=True,
                             check=True).stdout
    except (subprocess.CalledProcessError, OSError):
        return None
    tokens, rows = iter(raw.split(b"\0")), []
    for token in tokens:
        parts = token.split(b"\t", 2)
        if len(parts) < 3:
            continue
        path = parts[2]
        if not path:                                   # a rename: the old path, then the new one, follow
            next(tokens, b"")
            path = next(tokens, b"")
        added, removed = (int(x) if x.isdigit() else 0 for x in parts[:2])
        rows.append({"path": path.decode("utf-8", "replace"), "added": added, "removed": removed})
    return {"files": rows, "added": sum(r["added"] for r in rows), "removed": sum(r["removed"] for r in rows)}


def attributes_at(repo: Path, head: str, paths: list[str]) -> dict[str, str] | None:
    """git's own linguist-generated state for `paths` at `head` (`git check-attr --source`, git 2.40 and later): every
    .gitattributes in the tree, macros and quoting included. None when git cannot answer."""
    if not paths:
        return {}
    try:
        out = subprocess.run(["git", "check-attr", f"--source={head}", "-z", "--stdin", ATTRIBUTE], cwd=repo,
                             input=b"".join(p.encode() + b"\0" for p in paths), capture_output=True, check=True).stdout
    except (subprocess.CalledProcessError, OSError):
        return None
    fields = out.split(b"\0")
    return {fields[i].decode("utf-8", "replace"): fields[i + 2].decode("utf-8", "replace") for i in range(0, len(fields) - 2, 3)}


def measure_repo(repo: Path, base: str, head: str, regenerated: list[dict[str, Any]] | None = None
                 ) -> tuple[dict[str, Any] | None, dict[str, Any] | None]:
    """(diff statistics, measurement) for base..head in a checkout, reading only git. Falls back to the root
    .gitattributes text when this git has no `check-attr --source`."""
    stats = numstat(repo, base, head)
    if stats is None:
        return None, None
    attributes = attributes_at(repo, head, [f["path"] for f in stats["files"]])
    text = None
    if attributes is None:
        shown = subprocess.run(["git", "show", f"{head}:.gitattributes"], cwd=repo, capture_output=True, check=False)
        text = shown.stdout.decode("utf-8", "replace") if shown.returncode == 0 else ""
    return stats, measure(stats, gitattributes=text, attributes=attributes, regenerated=regenerated)


# ---------------------------------------------------------------------------------------------------- reporting

def whole(value: Any) -> int | None:
    """An integer count, including an integral float (JSON Schema's `integer` accepts 900.0)."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    return int(value) if isinstance(value, float) and value.is_integer() else None


def estimate_of(spec: dict[str, Any]) -> int | None:
    est = spec.get("estimated_lines")
    return whole(est.get("hand_written") if isinstance(est, dict) else est)


def flag(measured: dict[str, Any] | None, estimate: int | None, budget: dict[str, int]) -> str | None:
    """Why the change is over budget, for the owner; None when it is within it. Over budget means above size M, or in
    a bigger size than the spec estimated."""
    if not measured:
        return None
    lines, size = measured["hand_written"], size_for(measured["hand_written"], budget)
    if size == "L":
        why = f"{lines} hand-written lines is above size M (≤ {budget['M']})"
    elif estimate is not None and SIZES.index(size) > SIZES.index(size_for(estimate, budget)):
        why = f"{lines} hand-written lines is size {size}; the spec estimated {estimate} (size {size_for(estimate, budget)})"
    else:
        return None
    return f"Over budget: {why}."


def line(measured: dict[str, Any] | None, estimate: int | None, budget: dict[str, int]) -> str:
    """The pull request's size line: "N hand-written lines (app X, tests Y); G generated lines in <files>, regenerated
    by `<command>`.", plus the over-budget flag when there is one."""
    if not measured:
        return "Not measured for this change; the run record has the diff."
    text = f"{measured['hand_written']} hand-written lines (app {measured['app']}, tests {measured['tests']})"
    files = measured["generated_files"]
    if files:
        names = ", ".join(f"`{f['path']}`" for f in files[:3]) + (f" and {len(files) - 3} more" if len(files) > 3 else "")
        text += f"; {measured['generated']} generated lines in {names}"
        if measured["commands"]:
            text += ", regenerated by " + ", ".join(f"`{c}`" for c in measured["commands"])
    else:
        text += "; no generated files"
    text += "."
    if estimate is not None:
        text += f" Estimated {estimate} ({size_for(estimate, budget)}; {describe_budget(budget)})."
    over = flag(measured, estimate, budget)
    return f"{text} **{over}**" if over else text


